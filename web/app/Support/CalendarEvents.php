    /**
     * مناسبت‌های داخلی یک روز
     *
     * @param  array{0:int,1:int,2:int}  $jalali
     * @param  array{0:int,1:int,2:int}  $gregorian
     * @param  array{0:int,1:int,2:int}  $hijri
     * @param  int  $hijriMonthLength  ۲۹ یا ۳۰
     * @return array<int, array{title: string, kind: string, holiday: bool}>
     */
    public static function forDay(array $jalali, array $gregorian, array $hijri, int $hijriMonthLength = 30, bool $withIranian = true): array
    {
        $out = [];
        if ($withIranian) {
            foreach (self::SOLAR as [$m, $d, $title, $holiday]) {
                if ($jalali[1] === $m && $jalali[2] === $d) {
                    $out[] = ['title' => $title, 'kind' => 'national', 'holiday' => $holiday];
                }
            }
            foreach (self::HIJRI as [$m, $d, $title, $holiday]) {
                $day = min($d, $hijriMonthLength);
                if ($hijri[1] === $m && $hijri[2] === $day) {
                    $out[] = ['title' => $title, 'kind' => 'religious', 'holiday' => $holiday];
                }
            }
        }
        foreach (self::GREGORIAN as [$m, $d, $title]) {
            if ($gregorian[1] === $m && $gregorian[2] === $d) {
                $out[] = ['title' => $title, 'kind' => 'international', 'holiday' => false];
            }
        }

        return $out;
    }
